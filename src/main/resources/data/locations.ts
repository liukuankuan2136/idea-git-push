/**
 * 所有地名按长度降序排列（长名称优先匹配，避免"吉林"误匹配"吉林市"）。
 */
const SORTED_LOCATION_NAMES: string[] = Object.keys(LOCATION_MAP).sort(
  (a, b) => b.length - a.length
);

/**
 * 地区合规检查结果。
 */
export interface LocationMatch {
  /** 匹配到的地名 */
  name: string;
  /** 该地名所属省份 */
  province: string;
}

export interface RegionCheckResult {
  /** 按区域规则查出的异常地名 */
  regionViolations: LocationMatch[];
  /** 按实施项目规则查出的异常地名 */
  opsprojViolations: LocationMatch[];
  /** 是否有任何违规 */
  hasViolation: boolean;
}

/**
 * 从文本中提取所有匹配的中国地名。
 */
export function extractLocations(text: string): LocationMatch[] {
  if (!text) {
    return [];
  }

  const matches: LocationMatch[] = [];
  // 用已匹配区间避免重复（如"吉林市"已匹配后不再用"吉林"匹配同一位置）
  const covered = new Set<number>();

  for (const name of SORTED_LOCATION_NAMES) {
    let idx = 0;
    while (idx < text.length) {
      idx = text.indexOf(name, idx);
      if (idx === -1) { break; }

      // 检查是否被更长的地名覆盖
      const end = idx + name.length;
      let hasOverlap = false;
      for (let i = idx; i < end; i++) {
        if (covered.has(i)) {
          hasOverlap = true;
          break;
        }
      }

      if (!hasOverlap) {
        matches.push({ name, province: LOCATION_MAP[name] });
        for (let i = idx; i < end; i++) {
          covered.add(i);
        }
      }

      idx = end;
    }
  }

  return matches;
}

/**
 * 从实施项目名称中提取主要地名。
 * 取最长匹配，例如 "柳州法院" → { name: "柳州", province: "广西" }。
 */
export function extractPrimaryLocation(opsprojName: string): LocationMatch | undefined {
  if (!opsprojName) {
    return undefined;
  }

  const all = extractLocations(opsprojName);
  if (all.length === 0) {
    return undefined;
  }

  // 取最长匹配作为主要地点
  all.sort((a, b) => b.name.length - a.name.length);
  return all[0];
}

/**
 * 执行区域合规检查。
 *
 * @param taskName       任务名称
 * @param workContents   该任务下所有详细工时的 workContent 拼接
 * @param regionName     任务所属区域（如 "广西"、"共同区域"）
 * @param opsprojName    任务所属实施项目名称（如 "柳州法院"）
 */
export function checkRegionCompliance(
  taskName: string,
  workContents: string,
  regionName: string,
  opsprojName: string
): RegionCheckResult {
  const combinedText = `${taskName ?? ''} ${workContents ?? ''}`;
  const allLocations = extractLocations(combinedText);

  const regionViolations = checkRegionRule(allLocations, regionName);
  const opsprojViolations = checkOpsprojRule(allLocations, opsprojName);

  return {
    regionViolations,
    opsprojViolations,
    hasViolation: regionViolations.length > 0 || opsprojViolations.length > 0
  };
}

/**
 * 规则 A — 区域维度检查。
 */
function checkRegionRule(
  locations: LocationMatch[],
  regionName: string
): LocationMatch[] {
  if (!regionName || locations.length === 0) {
    return [];
  }

  const violations: LocationMatch[] = [];

  for (const loc of locations) {
    if (regionName === '共同区域') {
      // 共同区域：出现任何地名即违规
      violations.push(loc);
    } else {
      // 该地名是否属于当前区域对应的省份？
      // 先找到 regionName 对应的省份
      const regionProvince = LOCATION_MAP[regionName];
      if (regionProvince && loc.province !== regionProvince) {
        violations.push(loc);
      }
    }
  }

  return violations;
}

/**
 * 规则 B — 实施项目维度检查。
 * 从 opsprojName 中提取主要地点，检查是否出现其他地点。
 */
function checkOpsprojRule(
  locations: LocationMatch[],
  opsprojName: string
): LocationMatch[] {
  if (!opsprojName || locations.length === 0) {
    return [];
  }

  const primary = extractPrimaryLocation(opsprojName);
  if (!primary) {
    // 无法从实施项目名称中提取地名 → 无法判断，不标记
    return [];
  }

  const violations: LocationMatch[] = [];
  for (const loc of locations) {
    // 1. 同地名归一化（去掉"市""省"后缀后相同 → 视为同一地点，跳过）
    if (isSameLocation(loc.name, primary.name)) {
      continue;
    }

    // 2. 检测到的是 primary 所属的上级省份（如 primary=柳州(广西), loc=广西）→ 正常修饰，跳过
    if (loc.province === primary.province && isProvinceLevel(loc.name)) {
      continue;
    }

    // 其余：不同地点 → 违规
    violations.push(loc);
  }

  return violations;
}

/** 地名归一化比较：去掉"市""省"后缀后是否相同 */
function isSameLocation(a: string, b: string): boolean {
  const na = a.replace(/[市省]$/, '');
  const nb = b.replace(/[市省]$/, '');
  return na === nb;
}

/** 判断是否省份级地名（如"广西""河南"而非"柳州""南宁"） */
function isProvinceLevel(name: string): boolean {
  return LOCATION_MAP[name] === name;
}

/**
 * 判断一个 regionName 是否为合法的省份名（即不是"共同区域"这类特殊值）。
 */
export function isSpecificRegion(regionName: string): boolean {
  if (!regionName || regionName === '共同区域') {
    return false;
  }
  return regionName in LOCATION_MAP;
}
